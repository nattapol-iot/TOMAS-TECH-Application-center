import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { readFile,mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
const require=createRequire("C:/Users/natta/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json");
const {chromium}=require("playwright");
const root=new URL("../../",import.meta.url);
const pdf=await readFile(new URL("output/pdf/test-only-drawing.pdf",root));
const stamp=await readFile(new URL("output/pdf/test-only-stamp.png",root));
const signed=await readFile(new URL("output/pdf/test-only-positioned-drawing.pdf",root));
await mkdir(new URL("output/signing-preview",root),{recursive:true});
const browser=await chromium.launch({headless:true,channel:"msedge"});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1100}});const errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 await page.route("**/fixture/preview",r=>r.fulfill({json:{pdfBase64:pdf.toString("base64"),sourceSha256:"test-only-hash",pageCount:1,specimen:{id:1,imageBase64:stamp.toString("base64")},stampImageBase64:stamp.toString("base64"),legacyMarkCount:0}}));
 await page.route("**/fixture/output",r=>r.fulfill({body:signed,contentType:"application/pdf"}));
 await page.goto("http://127.0.0.1:3311/tests/ui/signing-preview.html");
 await page.locator("canvas").waitFor();
 await page.waitForFunction(()=>document.querySelector("canvas")?.width>0);
 await page.getByRole("checkbox").check();
 await page.getByRole("button",{name:/Use these positions/}).waitFor({state:"visible"});
 await page.waitForFunction(()=>!Array.from(document.querySelectorAll("button")).find(b=>b.textContent.includes("Use these positions"))?.disabled);
 const drag=page.getByRole("button",{name:/Move signature;/});await drag.hover();const initial=await drag.boundingBox();assert.ok(initial);
 await page.mouse.down();await page.mouse.move(initial.x+initial.width/2+60,initial.y+initial.height/2-35,{steps:8});await page.mouse.up();
 const moved=await drag.boundingBox();assert.ok(moved.x>initial.x+40);assert.ok(moved.y<initial.y-20);
 const resize=page.getByRole("button",{name:"Resize signature",exact:true});await resize.hover();const corner=await resize.boundingBox();assert.ok(corner);
 await page.mouse.down();await page.mouse.move(corner.x+corner.width/2+45,corner.y+corner.height/2+20,{steps:8});await page.mouse.up();
 assert.ok((await drag.boundingBox()).width>moved.width+30);
 await page.screenshot({path:fileURLToPath(new URL("output/signing-preview/edit.png",root)),fullPage:true});
 await page.getByRole("checkbox").check();await page.getByRole("button",{name:/Use these positions/}).click();
 const result=JSON.parse(await page.getByTestId("result").textContent());assert.ok(result.placement.width>.22);assert.equal(result.previewSpecimenId,1);assert.ok(result.stampPlacement);
 await page.getByRole("button",{name:"Signed preview",exact:true}).click();await page.locator("canvas").waitFor();
 await page.waitForFunction(()=>document.querySelectorAll("select option").length===2);
 await page.screenshot({path:fileURLToPath(new URL("output/signing-preview/signed.png",root)),fullPage:true});
 await page.getByRole("combobox").selectOption("2");await page.waitForTimeout(600);
 await page.screenshot({path:fileURLToPath(new URL("output/signing-preview/certificate.png",root)),fullPage:true});
 assert.equal(await page.locator(".sign-resize").count(),0);assert.ok(await page.getByRole("link",{name:"Download signed file"}).getAttribute("download"));
 await page.setViewportSize({width:420,height:900});await page.screenshot({path:fileURLToPath(new URL("output/signing-preview/mobile.png",root)),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log("UI PASSED: real PDF canvas + worker, drag, resize, confirmation, stamp selection, signed read-only preview, pagination, download and narrow viewport.");
}finally{await browser.close();}
