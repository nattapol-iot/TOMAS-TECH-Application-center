type DetailTab = "overview" | "requirement" | "meeting" | "estimate" | "attachments" | "activity";

export function InquiryDetail({ id, go, notify }: ScreenProps & { id: string }) {
  const inquiry = INQUIRIES.find((i) => i.id === id) ?? INQUIRIES[0];
  const customer = CUSTOMERS.find((c) => c.id === inquiry.customerId);
  const estimate = ESTIMATES.find((e) => e.id === inquiry.estimateId);
  const [tab, setTab] = useState<DetailTab>("overview");
  const [meetingOpen, setMeetingOpen] = useState(false);
  const [meetings, setMeetings] = useState(inquiry.meetings);

  return (
    <>
      <button className="back-link" type="button" onClick={() => go({ name: "inquiries" })}><Icon name="arrowLeft" />Inquiry Management</button>
      <PageHeader
        eyebrow={inquiry.no}
        title={`${customer?.code} — ${inquiry.projectName}`}
        subtitle={customer?.name}
        meta={
          <>
            <div><span>Inquiry status</span><strong><Badge tone={toneOf(inquiry.status)}>{inquiry.status}</Badge></strong></div>
            <div><span>Estimate due</span><strong>{formatDate(inquiry.dueDate)}</strong></div>
            <div><span>Estimate owner</span><strong>{userName(inquiry.estimateOwnerId)}</strong></div>
            <div><span>Priority</span><strong><Badge tone={PRIORITY_TONE[inquiry.priority]}>{inquiry.priority}</Badge></strong></div>
            <div><span>Project type</span><strong>{inquiry.projectType}</strong></div>
          </>
        }
        actions={
          <>
            {estimate ? (
              <button className="btn default" type="button" onClick={() => go({ name: "estimate", id: estimate.id })}>
                <Icon name="file" />Open estimate
              </button>
            ) : (
              <button className="btn primary" type="button" onClick={() => notify("Estimate EST-2608-0007 R00 created from this inquiry")}>
                <Icon name="plus" />Create estimate cost
              </button>
            )}
            <button className="btn default" type="button" onClick={() => notify("Estimate owner re-assigned")}><Icon name="user" />Assign owner</button>
          </>
        }
      />

      <Tabs
        active={tab}
        onChange={setTab}
        tabs={[
          { id: "overview", label: "Overview" },
          { id: "requirement", label: "Requirement" },
          { id: "meeting", label: "Meeting Log", count: meetings.length },
          { id: "estimate", label: "Estimate Cost", count: estimate ? 1 : 0 },
          { id: "attachments", label: "Attachments", count: inquiry.attachments.length },
          { id: "activity", label: "Activity" },
        ]}
      />

      {tab === "overview" ? <Overview inquiry={inquiry} estimate={estimate} go={go} /> : null}
      {tab === "requirement" ? <Requirement inquiry={inquiry} /> : null}
      {tab === "meeting" ? (
        <Panel
          title="Meeting Log"
          subtitle="Why the estimate requirement changed, recorded meeting by meeting"
          actions={<button className="btn primary sm" type="button" onClick={() => setMeetingOpen(true)}><Icon name="plus" />Add Meeting Record</button>}
        >
          {meetings.length ? (
            <div className="timeline">
              {meetings.map((meeting, index) => (
                <article className="timeline-item done" key={meeting.id}>
                  <div className="timeline-head">
                    <strong>{meeting.type}</strong>
                    <time>{formatDate(meeting.date)}</time>
                    <Pill>{`#${index + 1}`}</Pill>
                    <span className="spacer" />
                    <span className="muted">{meeting.participants.length} participants</span>
                  </div>
                  <div className="timeline-card">
                    <dl className="def-list">
                      <div><dt>Participants</dt><dd>{meeting.participants.join(", ")}</dd></div>
                      <div><dt>Customer requirement</dt><dd>{meeting.requirement}</dd></div>
                      <div><dt>Technical discussion</dt><dd>{meeting.technical}</dd></div>
                      <div><dt>Decision</dt><dd>{meeting.decision}</dd></div>
                      <div><dt>Open point</dt><dd>{meeting.openPoint || "—"}</dd></div>
                      <div><dt>Action item</dt><dd>{meeting.actionItem}</dd></div>
                      <div><dt>Owner</dt><dd>{meeting.owner}</dd></div>
                      <div><dt>Due date</dt><dd>{formatDate(meeting.dueDate)}</dd></div>
                    </dl>
                    {meeting.attachment ? (
                      <div className="file-row" style={{ marginTop: 10 }}>
                        <span className="file-icon"><Icon name="paperclip" /></span>
                        <div><strong>{meeting.attachment}</strong><small>Meeting Record</small></div>
                      </div>
                    ) : null}
                  </div>
                </article>
              ))}
            </div>
          ) : (
            <EmptyState icon="inbox" title="No meeting recorded yet" message="Add the kickoff meeting so engineers understand where the requirement came from."
              action={<button className="btn primary" type="button" onClick={() => setMeetingOpen(true)}><Icon name="plus" />Add Meeting Record</button>} />
          )}
        </Panel>
      ) : null}
      {tab === "estimate" ? <EstimateTab inquiry={inquiry} go={go} /> : null}
      {tab === "attachments" ? <Attachments inquiry={inquiry} /> : null}
      {tab === "activity" ? <Activity inquiry={inquiry} /> : null}

      {meetingOpen ? (
        <MeetingDrawer
          onClose={() => setMeetingOpen(false)}
          onSave={(record) => {
            setMeetings((prev) => [...prev, record]);
            setMeetingOpen(false);
            notify("Meeting record added to the inquiry");
          }}
        />
      ) : null}
    </>
  );
}

function Overview({ inquiry, estimate, go }: { inquiry: Inquiry; estimate?: (typeof ESTIMATES)[number]; go: ScreenProps["go"] }) {
  const customer = CUSTOMERS.find((c) => c.id === inquiry.customerId);
  const totals = estimate ? estimateTotals(estimate) : undefined;
  return (
    <section className="grid-main">
      <div className="stack">
        <Panel title="Inquiry information">
          <dl className="def-list">
            <div><dt>Inquiry No.</dt><dd className="mono">{inquiry.no}</dd></div>
            <div><dt>Inquiry date</dt><dd>{formatDate(inquiry.date)}</dd></div>
            <div><dt>Customer</dt><dd>{customer?.name}</dd></div>
            <div><dt>Customer contact</dt><dd>{inquiry.contact}</dd></div>
            <div><dt>Customer RFQ No.</dt><dd className="mono">{inquiry.rfqNo}</dd></div>
            <div><dt>Project type</dt><dd>{inquiry.projectType}</dd></div>
            <div><dt>Sales owner</dt><dd>{inquiry.salesOwner}</dd></div>
            <div><dt>Estimate owner</dt><dd>{userName(inquiry.estimateOwnerId)}</dd></div>
            <div><dt>Site location</dt><dd>{inquiry.siteLocation}</dd></div>
            <div><dt>Target delivery</dt><dd>{formatDate(inquiry.targetDelivery)}</dd></div>
          </dl>
        </Panel>
        <Panel title="Scope summary">
          <p style={{ fontSize: "var(--fs-sm)" }}>{inquiry.scopeSummary}</p>
          {inquiry.remark ? <div className="info-strip amber" style={{ marginTop: 12 }}><Icon name="alertTriangle" />{inquiry.remark}</div> : null}
        </Panel>
      </div>
      <div className="stack">
        <Panel title="Estimate progress">
          {estimate && totals ? (
            <>
              <dl className="def-list one">
                <div><dt>Estimate No.</dt><dd className="mono">{estimate.no} <span className="pill">{estimate.revision}</span></dd></div>
                <div><dt>Status</dt><dd><Badge tone={toneOf(estimate.status)}>{estimate.status}</Badge></dd></div>
                <div><dt>Total estimated cost</dt><dd><strong>{money(totals.total)}</strong></dd></div>
                <div><dt>Progress</dt><dd><ProgressCell value={estimate.progress} /></dd></div>
              </dl>
              <button className="btn default block" type="button" style={{ marginTop: 12 }} onClick={() => go({ name: "estimate", id: estimate.id })}>
                Open estimate workspace<Icon name="arrowRight" />
              </button>
            </>
          ) : (
            <EmptyState icon="file" title="No estimate yet" message="Create the estimate cost to start collecting engineering cost for this inquiry." />
          )}
        </Panel>
        <Panel title="Latest meetings">
          {inquiry.meetings.length ? (
            <ul className="check-list">
              {inquiry.meetings.slice(-3).reverse().map((meeting) => (
                <li className="check-item pass" key={meeting.id}>
                  <Icon name="checkCircle" />
                  <div>
                    <strong>{meeting.type} · {formatDate(meeting.date)}</strong>
                    <p>{meeting.decision}</p>
                  </div>
                </li>
              ))}
            </ul>
          ) : <p className="muted">No meeting recorded yet.</p>}
        </Panel>
      </div>
    </section>
  );
}

function Requirement({ inquiry }: { inquiry: Inquiry }) {
  const blocks: [string, string][] = [
    ["Customer Requirement", inquiry.requirement],
    ["Project Background", inquiry.background],
    ["Scope Summary", inquiry.scopeSummary],
    ["Technical Requirement", inquiry.technical],
    ["Customer Standard", inquiry.standard],
    ["Special Requirement", inquiry.special || "—"],
    ["Site Location", inquiry.siteLocation],
    ["Target Delivery", formatDate(inquiry.targetDelivery)],
    ["Remark", inquiry.remark || "—"],
  ];
  return (
    <Panel title="Requirement Information" subtitle="Frozen with each revision so engineers can see what the cost was based on">
      <dl className="def-list">
        {blocks.map(([label, value]) => (
          <div key={label} style={label === "Customer Requirement" || label === "Technical Requirement" ? { gridColumn: "span 2" } : undefined}>
            <dt>{label}</dt>
            <dd>{value}</dd>
          </div>
        ))}
      </dl>
    </Panel>
  );
}

function EstimateTab({ inquiry, go }: { inquiry: Inquiry; go: ScreenProps["go"] }) {
  const estimate = ESTIMATES.find((e) => e.id === inquiry.estimateId);
  if (!estimate) {
    return (
      <Panel>
        <EmptyState icon="file" title="No estimate cost created" message="Create an estimate to divide the engineering scope and start collecting cost." />
      </Panel>
    );
  }
  const totals = estimateTotals(estimate);
  return (
    <Panel title="Estimate cost linked to this inquiry" flush>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Estimate No.</th><th>Rev.</th><th>Owner</th><th>Created</th><th>Due</th>
              <th className="num">Material</th><th className="num">Engineering</th><th className="num">Outsource</th>
              <th className="num">Other</th><th className="num">Total</th><th>Progress</th><th>Status</th><th aria-label="Action" />
            </tr>
          </thead>
          <tbody>
            {estimate.revisions.map((revision, index) => {
              const isCurrent = index === estimate.revisions.length - 1;
              return (
                <tr key={revision.id} className={isCurrent ? "clickable" : undefined} onClick={isCurrent ? () => go({ name: "estimate", id: estimate.id }) : undefined}>
                  <td><strong className="mono">{estimate.no}</strong></td>
                  <td><span className="pill">{revision.code}</span></td>
                  <td>{revision.createdBy}</td>
                  <td>{formatDate(revision.createdAt)}</td>
                  <td>{formatDate(estimate.dueDate)}</td>
                  <td className="num">{isCurrent ? moneyShort(totals.material) : "—"}</td>
                  <td className="num">{isCurrent ? moneyShort(totals.engineering) : "—"}</td>
                  <td className="num">{isCurrent ? moneyShort(totals.outsource) : "—"}</td>
                  <td className="num">{isCurrent ? moneyShort(totals.other + totals.transportation + totals.accommodation) : "—"}</td>
                  <td className="num"><strong>{moneyShort(isCurrent ? totals.total : revision.total)}</strong></td>
                  <td style={{ minWidth: 110 }}>{isCurrent ? <ProgressCell value={estimate.progress} /> : <span className="muted">Closed</span>}</td>
                  <td><Badge tone={toneOf(isCurrent ? estimate.status : revision.status)}>{isCurrent ? estimate.status : revision.status}</Badge></td>
                  <td>{isCurrent ? <span className="row-action"><Icon name="chevronRight" /></span> : null}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </Panel>
  );
}

