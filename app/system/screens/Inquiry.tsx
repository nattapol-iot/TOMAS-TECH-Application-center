"use client";

import { useMemo, useState } from "react";
import {
  AUDIT_LOG, CUSTOMERS, ESTIMATES, INQUIRIES, PROJECT_TYPES, USERS,
  type Inquiry, type Priority,
} from "../data";
import { estimateTotals, formatDate, money, moneyShort, TODAY, userName, userOf } from "../calc";
import {
  Badge, Drawer, EmptyState, Field, GridControls, Icon, Pagination, Panel, PageHeader,
  Person, Pill, ProgressCell, SearchInput, Select, StatusLegend, Tabs, Toolbar, toneOf, usePaged,
} from "../ui";
import { useT } from "../i18n";
import type { ScreenProps } from "../routes";

const FILE_CATEGORIES = [
  "Customer RFQ", "Meeting Record", "Specification", "Drawing", "Layout",
  "Equipment List", "Customer Standard", "Supplier Document", "Reference Document", "Other",
];

const PRIORITY_TONE: Record<Priority, "red" | "amber" | "blue" | "slate"> = {
  Urgent: "red", High: "amber", Normal: "blue", Low: "slate",
};

/* ==========================================================================
   Inquiry list
   ========================================================================== */

export function InquiryList({ go }: ScreenProps) {
  const [search, setSearch] = useState("");
  const [customer, setCustomer] = useState("All customers");
  const [type, setType] = useState("All project types");
  const [owner, setOwner] = useState("All owners");
  const [status, setStatus] = useState("All status");
  const [priority, setPriority] = useState("All priorities");
  const [pageSize, setPageSize] = useState(50);
  const [page, setPage] = useState(1);
  const t = useT();

  const rows = useMemo(() => INQUIRIES.filter((inquiry) => {
    const customerRecord = CUSTOMERS.find((c) => c.id === inquiry.customerId);
    const haystack = `${inquiry.no} ${inquiry.projectName} ${customerRecord?.name} ${inquiry.rfqNo}`.toLowerCase();
    if (search && !haystack.includes(search.toLowerCase())) return false;
    if (customer !== "All customers" && customerRecord?.code !== customer) return false;
    if (type !== "All project types" && inquiry.projectType !== type) return false;
    if (owner !== "All owners" && userName(inquiry.estimateOwnerId) !== owner) return false;
    if (status !== "All status" && inquiry.status !== status) return false;
    if (priority !== "All priorities" && inquiry.priority !== priority) return false;
    return true;
  }), [search, customer, type, owner, status, priority]);

  const paged = usePaged(rows, pageSize, page);

  return (
    <>
      <PageHeader
        eyebrow={t("SALES TO ENGINEERING")}
        title={t("Inquiry Management")}
        subtitle={t("Every customer inquiry is registered here and receives a unique inquiry number automatically.")}
        actions={<button className="btn primary" type="button" onClick={() => go({ name: "inquiry-new" })}><Icon name="plus" />{t("New Inquiry")}</button>}
      />

      <Toolbar>
        <SearchInput value={search} onChange={setSearch} placeholder="Search inquiry no., project, customer or RFQ no.…" />
        <Select label="Customer" value={customer} onChange={setCustomer} options={["All customers", ...CUSTOMERS.map((c) => c.code)]} />
        <Select label="Project type" value={type} onChange={setType} options={["All project types", ...PROJECT_TYPES]} />
        <Select label="Estimate owner" value={owner} onChange={setOwner} options={["All owners", ...USERS.filter((u) => u.role === "Engineer").map((u) => u.name)]} />
        <Select label="Status" value={status} onChange={setStatus} options={["All status", "New", "Estimating", "Waiting Supplier Price", "Estimate Completed", "Engineering Review", "Approved"]} />
        <Select label="Priority" value={priority} onChange={setPriority} options={["All priorities", "Urgent", "High", "Normal", "Low"]} />
        <button className="btn ghost" type="button"><Icon name="calendar" />Inquiry date</button>
        <button className="btn ghost" type="button"><Icon name="calendar" />Due date</button>
      </Toolbar>

      <StatusLegend items={[
        { label: "New", kind: "new" },
        { label: "Estimating", kind: "revised" },
        { label: "Waiting supplier price", kind: "wait" },
        { label: "Engineering review", kind: "approved" },
        { label: "Approved", kind: "confirmed" },
        { label: "Overdue", kind: "canceled" },
      ]} />

      <Panel title={`${rows.length} inquiries`} subtitle="Inquiry numbers are generated by the system and can never duplicate" flush>
        <GridControls pageSize={pageSize} onPageSize={(size) => { setPageSize(size); setPage(1); }} search={search} onSearch={(value) => { setSearch(value); setPage(1); }} />
        {rows.length ? (
          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>{t("Inquiry No.")}</th>
                  <th>{t("Inquiry Date")}</th>
                  <th>{t("Customer")}</th>
                  <th>{t("Project Name")}</th>
                  <th>{t("Project Type")}</th>
                  <th>{t("Sales Owner")}</th>
                  <th>{t("Estimate Owner")}</th>
                  <th>{t("Estimate Due")}</th>
                  <th>{t("Progress")}</th>
                  <th>{t("Rev.")}</th>
                  <th>{t("Priority")}</th>
                  <th>{t("Status")}</th>
                  <th>{t("Last Updated")}</th>
                  <th aria-label="Action" />
                </tr>
              </thead>
              <tbody>
                {paged.pageRows.map((inquiry) => {
                  const customerRecord = CUSTOMERS.find((c) => c.id === inquiry.customerId);
                  const late = new Date(inquiry.dueDate) < TODAY && inquiry.status !== "Approved";
                  return (
                    <tr
                      key={inquiry.id}
                      className={`clickable ${late ? "row-late" : inquiry.status === "Approved" || inquiry.status === "Estimate Completed" ? "row-ok" : inquiry.status === "Waiting Supplier Price" ? "row-wait" : ""}`}
                      onClick={() => go({ name: "inquiry", id: inquiry.id })}
                    >
                      <td><strong className="mono">{inquiry.no}</strong></td>
                      <td>{formatDate(inquiry.date)}</td>
                      <td>
                        <div className="cell-primary">
                          <strong>{customerRecord?.code}</strong>
                          <span>{customerRecord?.name}</span>
                        </div>
                      </td>
                      <td><strong>{inquiry.projectName}</strong></td>
                      <td>{inquiry.projectType}</td>
                      <td>{inquiry.salesOwner}</td>
                      <td><Person initials={userOf(inquiry.estimateOwnerId)?.initials ?? "—"} name={userName(inquiry.estimateOwnerId)} /></td>
                      <td className={late ? "red-text" : undefined}>{formatDate(inquiry.dueDate)}</td>
                      <td style={{ minWidth: 110 }}><ProgressCell value={inquiry.progress} /></td>
                      <td><span className="pill">{inquiry.revision}</span></td>
                      <td><Badge tone={PRIORITY_TONE[inquiry.priority]}>{inquiry.priority}</Badge></td>
                      <td><Badge tone={toneOf(inquiry.status)}>{inquiry.status}</Badge></td>
                      <td className="muted">{inquiry.updatedAt}</td>
                      <td><span className="row-action"><Icon name="chevronRight" /></span></td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
            <Pagination page={paged.current} pageCount={paged.pageCount} from={paged.from} to={paged.to} total={paged.total} onPage={setPage} />
          </div>
        ) : (
          <EmptyState icon="inbox" title="No inquiry matches the filter" message="Adjust the filters above or register a new customer inquiry." />
        )}
      </Panel>
    </>
  );
}

